from typing import List
from src.models.comment.comment import Comment
from src.models.project.project import Project
from src.models.task.task import Task


class PromptBuilder:
    @staticmethod
    def build_user_prompt(project: Project, comment: Comment, tasks: List[Task]) -> str:
        if tasks:
            formatted_tasks_blocks = []
            for idx, task in enumerate(tasks, start=1):
                block = f"=== ЗАДАЧА {idx} ===\nНазвание: {task.title}\n"
                if task.description_md:
                    block += f"\n{task.description_md}"
                formatted_tasks_blocks.append(block)
            formatted_tasks = "\n\n".join(formatted_tasks_blocks)
        else:
            formatted_tasks = ""

        parts = [
            f"=== МЕТАДАННЫЕ ===\nСтатья: {project.title or '[не указано]'}\nЖурнал: {project.journal or '[не указано]'}",
            f"=== ЗАМЕЧАНИЕ ===\n{comment.content_md}",
        ]
        if formatted_tasks:
            parts.append(formatted_tasks)

        return "\n\n".join(parts)
    
